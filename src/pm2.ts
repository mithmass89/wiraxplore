// src/pm2.ts
import { existsSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { log } from './utils/logger.js';

export const ECOSYSTEM_FILE = 'ecosystem.config.cjs';
export const PM2_APP_NAME = 'wiraxplore-lightpanda';

export interface Pm2Options {
  host?: string;
  port?: number;
  protocol?: string;
  obeyRobots?: boolean;
}

function packageRoot(): string {
  return join(dirname(fileURLToPath(import.meta.url)), '..');
}

/**
 * The equivalent of the ecosystem entry, for humans and for `doctor`.
 */
export function resolveCliCommand(projectDir: string = process.cwd()): string[] {
  return [process.execPath, resolveCliScript(projectDir), 'serve'];
}

/**
 * The JS entrypoint PM2 should run. Prefers the project-local install so the app
 * repo pins its own version, and falls back to this checkout.
 */
export function resolveCliScript(projectDir: string = process.cwd()): string {
  const local = join(projectDir, 'node_modules', 'wiraxplore', 'bin', 'wiraxplore.js');
  if (existsSync(local)) return local;
  return join(packageRoot(), 'bin', 'wiraxplore.js');
}

export function renderEcosystem(projectDir: string, opts: Pm2Options = {}): string {
  const script = resolveCliScript(projectDir);
  const args = ['serve'];
  if (opts.protocol) args.push('--protocol', opts.protocol);
  if (opts.host || opts.port) {
    args.push('--host', opts.host ?? '127.0.0.1', '--port', String(opts.port ?? 9222));
  }

  return `// Generated by \`wiraxplore pm2 init\`. Regenerate instead of editing by hand.
const path = require('node:path');

module.exports = {
  apps: [
    {
      name: '${PM2_APP_NAME}',
      script: ${JSON.stringify(script)},
      args: ${JSON.stringify(args)},
      cwd: ${JSON.stringify(projectDir)},
      // PM2 prepends \`node\` because the script is a .js file.
      autorestart: true,
      max_restarts: 10,
      restart_delay: 2000,
      kill_timeout: 5000,
      merge_logs: true,
      time: true,
      out_file: path.join(${JSON.stringify(projectDir)}, '.wiraxplore.out.log'),
      error_file: path.join(${JSON.stringify(projectDir)}, '.wiraxplore.err.log'),
      env: {
        LIGHTPANDA_DISABLE_TELEMETRY: 'true',
      },
    },
  ],
};
`;
}

export function writeEcosystem(projectDir: string = process.cwd(), opts: Pm2Options = {}): string {
  const file = join(projectDir, ECOSYSTEM_FILE);
  writeFileSync(file, renderEcosystem(projectDir, opts), 'utf8');
  return file;
}

export function pm2Available(): boolean {
  const probe = spawnSync('pm2', ['--version'], { encoding: 'utf8', shell: process.platform === 'win32' });
  return probe.status === 0;
}

export function runPm2(args: string[], cwd: string = process.cwd()): { ok: boolean; output: string } {
  const result = spawnSync('pm2', args, {
    cwd,
    encoding: 'utf8',
    stdio: 'inherit',
    shell: process.platform === 'win32',
  });
  return { ok: result.status === 0, output: `${result.stdout ?? ''}${result.stderr ?? ''}`.trim() };
}

export interface Pm2ActionResult {
  ok: boolean;
  steps: string[];
}

export function pm2Start(projectDir: string, opts: Pm2Options = {}): Pm2ActionResult {
  const steps: string[] = [];
  const eco = join(projectDir, ECOSYSTEM_FILE);
  if (!existsSync(eco)) {
    writeEcosystem(projectDir, opts);
    steps.push(`wrote ${ECOSYSTEM_FILE}`);
  }

  runPm2(['start', ECOSYSTEM_FILE, '--update-env'], projectDir);
  runPm2(['save'], projectDir);
  steps.push(`pm2 started ${PM2_APP_NAME}`, 'pm2 save');
  return { ok: true, steps };
}

export function requirePm2(): void {
  if (!pm2Available()) {
    log.error('pm2 is not installed. Install it with: npm i -g pm2');
    process.exit(1);
  }
}
